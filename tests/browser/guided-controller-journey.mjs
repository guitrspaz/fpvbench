import { fullControllerExport } from '../helpers/controller-fixtures.mjs';
/** The only mapping mutation is the explicit final physical-check save. */
export async function runGuidedControllerJourney({page,expect,baseURL,screenshotDir}){
  const post=async(path,data)=>{const r=await page.request.post(baseURL+path,{data});expect(r.ok()).toBe(true);return r.json();};
  const aircraft=await post('/api/aircraft',{name:'Guided control example'});
  const original=await post('/api/snapshots',{aircraftId:aircraft.id,label:'Original check example',filename:'synthetic.txt',rawText:fullControllerExport({0:'0 3 1700 2100 0 0'})});
  const prior=await post('/api/snapshots',{aircraftId:aircraft.id,label:'Previous check example',filename:'synthetic.txt',rawText:fullControllerExport({0:'0 3 1300 2100 0 0'})});
  const latest=await post('/api/snapshots',{aircraftId:aircraft.id,label:'Current check example',filename:'synthetic.txt',rawText:fullControllerExport({0:'0 3 1700 2100 0 0',1:'13 4 1700 2100 0 0'})});
  const preferred=await page.request.patch(baseURL+'/api/aircraft/'+aircraft.id,{data:{baselineSnapshotId:original.id}});expect(preferred.ok()).toBe(true);
  await post('/api/sessions',{aircraftId:aircraft.id,title:'Explicit confirmed flight',snapshotId:original.id,confirmedSetup:true,flownAt:new Date(Date.parse(latest.importedAt)-1000).toISOString()});
  await post('/api/sessions',{aircraftId:aircraft.id,title:'Unconfirmed flight',snapshotId:prior.id,confirmedSetup:false,flownAt:new Date(Date.parse(latest.importedAt)-100).toISOString()});
  await page.reload();await page.getByLabel('Selected aircraft').selectOption(aircraft.id);
  await page.getByRole('button',{name:'My controller',exact:true}).click();
  const panel=page.getByRole('region',{name:'Controller 3 map',exact:true});
  await page.getByRole('button',{name:'Last confirmed flight before this import',exact:true}).click();
  await expect(page.getByLabel('Controller reference')).toHaveValue(original.id);
  await expect(page.getByText(/Flight reference: Explicit confirmed flight/)).toBeVisible();
  await page.getByRole('button',{name:'Previous import',exact:true}).click();
  await expect(page.getByLabel('Controller reference')).toHaveValue(prior.id);
  await page.getByRole('button',{name:'Preferred setup',exact:true}).click();
  await expect(page.getByLabel('Controller reference')).toHaveValue(original.id);
  await panel.locator('[data-control="start-stop"]').click();
  const guide=panel.getByRole('region',{name:'Guided button check',exact:true});
  await guide.getByRole('button',{name:'Check this control',exact:true}).click();
  await expect(guide.getByLabel('Channel observed')).toHaveValue('');
  await guide.getByLabel('Channel observed').selectOption('4');
  await guide.getByRole('button',{name:'Continue',exact:true}).click();
  await guide.getByRole('button',{name:'Continue',exact:true}).click();
  await expect(guide.getByRole('alert')).toContainText('two to five');
  await guide.getByRole('button',{name:'Leave unfinished',exact:true}).click();
  const untouched=await(await page.request.get(baseURL+'/api/snapshots/'+latest.id)).json();
  expect(untouched.controller).toBeUndefined();
  await guide.getByRole('button',{name:'Check this control',exact:true}).click();
  await guide.getByLabel('Channel observed').selectOption('4');
  await guide.getByRole('button',{name:'Continue',exact:true}).click();
  await guide.getByLabel('Position 1 name').fill('Released');
  await guide.getByLabel('Position 1 value').fill('1000');
  await guide.getByLabel('Position 2 name').fill('Pressed');
  await guide.getByLabel('Position 2 value').fill('2000');
  await guide.getByRole('button',{name:'Continue',exact:true}).click();
  await guide.getByRole('button',{name:'Save checked control',exact:true}).click();
  await expect(guide.getByRole('alert')).toContainText('selected backup');
  await guide.getByLabel('I am checking the aircraft configuration saved in this selected backup.',{exact:true}).check();
  await guide.getByRole('button',{name:'Save checked control',exact:true}).click();
  await expect(guide.getByRole('alert')).toContainText('Confirm your own check');
  await guide.getByLabel('I checked this physical control and all positions or states recorded here.',{exact:true}).check();
  await guide.getByRole('button',{name:'Save checked control',exact:true}).click();
  await expect(panel.locator('[data-control="start-stop"]')).toContainText('Checked on controller');
  const saved=await(await page.request.get(baseURL+'/api/snapshots/'+latest.id)).json();
  expect(Object.keys(saved.controller.controls)).toEqual(['start-stop']);
  expect(saved.controller.controls['start-stop']).toMatchObject({verified:true,aux:4,positions:[{label:'Released',value:1000},{label:'Pressed',value:2000}]});
  const originalSaved=await(await page.request.get(baseURL+'/api/snapshots/'+original.id)).json();
  expect(originalSaved.controller).toBeUndefined();
  await page.reload();await page.getByRole('button',{name:'My controller',exact:true}).click();
  await expect(panel.locator('[data-control="start-stop"]')).toContainText('Checked on controller');
  const event=page.waitForEvent('download');await panel.getByRole('button',{name:'Download control card',exact:true}).click();const download=await event;
  expect(download.suggestedFilename()).toBe('fpvbench-control-card.html');
  const stream=await download.createReadStream();const chunks=[];for await(const chunk of stream)chunks.push(chunk);
  const html=Buffer.concat(chunks).toString('utf8');
  expect(html).toContain('Current check example');expect(html).toContain('Checked for this setup');expect(html).toContain('Expected assignment · not checked');
  expect(html).not.toMatch(/<script|rawText|synthetic.txt/);
  const card=await page.context().newPage();try{
    await card.setViewportSize({width:390,height:844});await card.setContent(html);
    await expect(card.getByRole('heading',{name:'Guided control example · Controller 3',exact:true})).toBeVisible();
    expect(await card.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
    await card.emulateMedia({media:'print'});await expect(card.locator('article')).toHaveCount(8);
    if(screenshotDir)await card.screenshot({path:screenshotDir+'/fpvbench-control-card-mobile.png',fullPage:true});
  }finally{await card.close();}
  await page.setViewportSize({width:390,height:844});
  await panel.locator('[data-control="start-stop"]').click();await guide.getByRole('button',{name:'Check this control',exact:true}).click();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
  const addBox=await page.getByRole('button',{name:'+ Add aircraft',exact:true}).boundingBox();
  const editBox=await page.getByRole('button',{name:'Edit aircraft',exact:true}).boundingBox();
  expect(addBox.y+addBox.height<=editBox.y).toBe(true);
  if(screenshotDir)await page.screenshot({path:screenshotDir+'/fpvbench-guided-check-mobile.png',fullPage:true});
  await guide.getByRole('button',{name:'Leave unfinished',exact:true}).click();
  await page.setViewportSize({width:1440,height:1000});
  return {passed:['explicit last-flown reference','previous and preferred shortcuts','cancel saves nothing','missing positions rejected','two explicit acknowledgments required','only checked control saved','reload retains verification','private offline card download','mobile and print card','mobile guided check']};
}
