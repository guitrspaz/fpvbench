/** Aircraft lifecycle using a synthetic memory-backed workspace. */
export async function runStatusJourney({ page, expect, baseURL, baselineText }) {
  const errors = [];
  const onError = error => errors.push(error.message);
  page.on('pageerror', onError);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await expect(page.getByLabel('Fleet status filter')).toHaveValue('active');
  await page.getByRole('button', { name: '+ Add aircraft', exact: true }).click();
  const add = page.getByRole('dialog', { name: 'Add an aircraft' });
  await expect(add.getByLabel('Aircraft status')).toHaveValue('active');
  await add.getByLabel('Aircraft name').fill('Lifecycle old quad');
  await add.getByLabel('Serial number').fill('LIFECYCLE-OLD');
  await add.getByRole('button', { name: 'Add aircraft', exact: true }).click();
  await expect(add).not.toBeVisible();
  await expect(page.getByLabel('Selected aircraft').locator('option:checked')).toHaveText('Lifecycle old quad');
  const oldId = await page.getByLabel('Selected aircraft').inputValue();
  await page.locator('.heading-actions').getByRole('button', { name: '↑ Import setup', exact: true }).click();
  const imported = page.getByRole('dialog', { name: 'Import Betaflight setup' });
  await imported.getByLabel('Setup label').fill('Lifecycle reference');
  await imported.getByLabel('Or paste the CLI export').fill(baselineText);
  await imported.getByRole('button', { name: 'Save snapshot', exact: true }).click();
  await expect(imported).not.toBeVisible();
  await page.getByRole('button', { name: 'Set as baseline', exact: true }).click();
  await page.getByRole('button', { name: '+ Log a flight', exact: true }).click();
  const session = page.getByRole('dialog', { name: 'Log a flight session' });
  await session.getByLabel('Session title').fill('Lifecycle historical flight');
  await session.getByLabel('Flight date and time').fill('2026-10-14T14:30');
  await session.getByLabel('Setup used').selectOption({ label: 'Lifecycle reference' });
  await session.getByLabel('Observations').fill('Keep these historical observations');
  await session.getByRole('button', { name: 'Save session', exact: true }).click();
  await expect(session).not.toBeVisible();
  const before = await (await page.request.get(baseURL + '/api/state')).json();
  await page.getByRole('button', { name: 'Edit aircraft', exact: true }).click();
  const edit = page.getByRole('dialog', { name: 'Edit aircraft', exact: true });
  await edit.getByLabel('Aircraft status').selectOption('retired');
  await edit.getByRole('button', { name: 'Save aircraft', exact: true }).click();
  await expect(edit).not.toBeVisible();
  await expect(page.getByLabel('Selected aircraft').locator(`option[value="${oldId}"]`)).toHaveCount(0);
  const retired = await (await page.request.get(baseURL + '/api/state')).json();
  expect(retired.aircraft.find(aircraft => aircraft.id === oldId).status).toBe('retired');
  expect(retired.snapshots).toEqual(before.snapshots);
  expect(retired.sessions).toEqual(before.sessions);
  expect(retired.aircraft.find(aircraft => aircraft.id === oldId).baselineSnapshotId).toBe(before.aircraft.find(aircraft => aircraft.id === oldId).baselineSnapshotId);
  await page.getByLabel('Fleet status filter').selectOption('retired');
  await expect(page.getByLabel('Selected aircraft')).toHaveValue(oldId);
  await expect(page.getByText('RETIRED', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: /Flight sessions/ }).click();
  await expect(page.getByText('Keep these historical observations', { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByLabel('Fleet status filter')).toHaveValue('retired');
  await expect(page.getByLabel('Selected aircraft')).toHaveValue(oldId);
  await page.getByLabel('Fleet status filter').selectOption('all');
  await expect(page.getByLabel('Selected aircraft').locator(`option[value="${oldId}"]`)).toHaveText('Lifecycle old quad (Retired)');
  await page.getByLabel('Fleet status filter').selectOption('retired');
  await page.getByRole('button', { name: 'Edit aircraft', exact: true }).click();
  await expect(edit.getByLabel('Aircraft status')).toHaveValue('retired');
  await edit.getByLabel('Aircraft status').selectOption('active');
  await edit.getByRole('button', { name: 'Save aircraft', exact: true }).click();
  await expect(edit).not.toBeVisible();
  await expect(page.getByRole('heading', { name: 'No retired aircraft', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Show all aircraft', exact: true }).click();
  await page.getByLabel('Fleet status filter').selectOption('active');
  await page.getByLabel('Selected aircraft').selectOption(oldId);
  await expect(page.getByText('ACTIVE', { exact: true })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  expect(errors).toEqual([]);
  page.off('pageerror', onError);
  return { passed: ['active default', 'retirement excludes active selector', 'retirement retains linked history', 'retired history view', 'filter reload persistence', 'all-aircraft status labels', 'reactivation', 'empty filtered fleet', 'mobile fleet filter'], errors };
}
