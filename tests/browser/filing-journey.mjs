import {writeFile,readFile} from 'node:fs/promises';
import {join} from 'node:path';
import {decodedDjiFixture} from '../helpers/dji-fixtures.mjs';

/** Read-only scans and explicit imports of disposable files; no database or live provider. */
export async function runFilingJourney({page,expect,baseURL,folder,screenshotDir,provider,airdata}) {
  const beforeAi=provider.calls.length,beforeAirdata=airdata.calls.length,errors=[];
  const onError=error=>errors.push(error.message);page.on('pageerror',onError);
  const request=async(path,input,method='POST')=>{
    const response=await page.request.fetch(baseURL+path,{method,data:input});expect(response.ok()).toBe(true);return response.json();
  };
  const state=async()=>(await page.request.get(baseURL+'/api/state')).json();
  const aircraft=await request('/api/aircraft',{name:'Filing test aircraft',serialNumber:'FILING-SERIAL'});
  const fixture=decodedDjiFixture();fixture.details.aircraftSerial='FILING-SERIAL';
  const routed=Buffer.from(JSON.stringify(fixture));
  const known=Buffer.from('synthetic retained Remote ID bytes');
  const ulog=Buffer.alloc(16);Buffer.from([0x55,0x4c,0x6f,0x67,1,0x12,0x35]).copy(ulog);
  await request('/api/log-imports',{filename:'original-name.ridlog',contentBase64:known.toString('base64')});
  for(const [name,bytes] of [['a-routed.json',routed],['b-extra.json',routed],['c-unknown.ridlog',Buffer.from('unknown identity')],['d-renamed.ridlog',known],['e-malformed.json',Buffer.from('{invalid JSON')]])await writeFile(join(folder,name),bytes);
  await writeFile(join(folder,'f-eligible.ulg'),ulog);
  const before=await state();
  await page.getByRole('button',{name:/Flight log library/}).click();
  await page.getByRole('button',{name:'Review flight-record folder',exact:true}).click();
  await expect(page.getByLabel('Flight-record folder',{exact:true})).toHaveValue(folder);
  await expect(page.getByText('Choose a folder and scan it to begin.',{exact:true})).toBeVisible();
  expect(await(await page.request.get(baseURL+'/api/filing/scan')).json()).toBeNull();
  await page.getByRole('button',{name:'Scan folder',exact:true}).click();
  await expect(page.getByText('Folder scan ready. Select files to import.',{exact:true})).toBeVisible();
  expect(await state()).toEqual(before);
  const rows=page.locator('#filing-rows .filing-file');
  await expect(rows).toHaveCount(6);
  await expect(page.getByLabel('Select b-extra.json',{exact:true})).toBeDisabled();
  await expect(page.getByLabel('Select d-renamed.ridlog',{exact:true})).toBeDisabled();
  await page.getByLabel('Filter folder review').selectOption('duplicates');
  await expect(rows).toHaveCount(1);
  await page.getByLabel('Filter folder review').selectOption('new');
  await expect(rows).toHaveCount(4);
  await page.getByRole('button',{name:'Select matching new files',exact:true}).click();
  await expect(page.getByText('4 selected',{exact:true})).toBeVisible();
  await page.locator('#filing-review').getByLabel('Source device (optional)',{exact:true}).fill('Synthetic shared goggles');
  await page.getByRole('button',{name:'Import selected files',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Import results',exact:true})).toBeVisible();
  await expect(page.getByText('a-routed.json: Imported and assigned',{exact:true})).toBeVisible();
  await expect(page.getByText('c-unknown.ridlog: Imported; assignment needed',{exact:true})).toBeVisible();
  expect((await state()).flightLogs).toHaveLength(before.flightLogs.length+3);
  const after=await state();
  expect(after.flightLogs.find(log=>log.filename==='a-routed.json')?.aircraftId).toBe(aircraft.id);
  await page.getByLabel('Filter folder review').selectOption('unassigned');
  await expect(rows).toHaveCount(3);
  const unassigned=after.flightLogs.find(log=>log.filename==='c-unknown.ridlog');
  await request('/api/flight-logs/'+unassigned.id,{aircraftId:aircraft.id},'PATCH');
  await page.getByRole('button',{name:'Refresh saved statuses',exact:true}).click();
  await expect(rows).toHaveCount(2);
  await expect(page.getByLabel('Filter folder review').locator('option')).toHaveText(['All reviewed files','New originals','Already imported','Extra copies','Unassigned imports','Blocked files']);
  await expect(page.locator('#filing-review')).not.toContainText('AirData');
  await writeFile(join(folder,'late.ridlog'),'arrived after the snapshot');
  await page.reload();
  await page.getByRole('button',{name:/Flight log library/}).click();
  await page.getByRole('button',{name:'Review flight-record folder',exact:true}).click();
  await page.getByLabel('Filter folder review').selectOption('all');
  await expect(rows).toHaveCount(6);
  await expect(page.getByRole('heading',{name:'late.ridlog',exact:true})).toHaveCount(0);
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  if(screenshotDir)await page.screenshot({path:screenshotDir+'/filing-mobile.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  if(screenshotDir)await page.screenshot({path:screenshotDir+'/filing-desktop.png',fullPage:true});
  for(let i=0;i<22;i++)await writeFile(join(folder,`batch-${i}.ridlog`),`Synthetic batch original ${i}`);
  await page.getByRole('button',{name:'Scan folder',exact:true}).click();
  await expect(rows).toHaveCount(29);
  await page.getByLabel('Filter folder review').selectOption('new');
  await page.getByRole('button',{name:'Select matching new files',exact:true}).click();
  await expect(page.getByText('24 selected',{exact:true})).toBeVisible();
  const batches=[];const onRequest=request=>{if(request.url()===baseURL+'/api/filing/import')batches.push(request.postDataJSON().fileIds.length);};
  page.on('request',onRequest);
  await page.getByRole('button',{name:'Import selected files',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Import results',exact:true})).toBeVisible();
  await expect(page.getByText('late.ridlog: Imported; assignment needed',{exact:true})).toBeVisible();
  page.off('request',onRequest);expect(batches).toEqual([20,4]);
  expect((await state()).flightLogs).toHaveLength(before.flightLogs.length+26);
  expect(await readFile(join(folder,'a-routed.json'))).toEqual(routed);
  expect(await readFile(join(folder,'d-renamed.ridlog'))).toEqual(known);
  const exported=await(await page.request.get(baseURL+'/api/export')).text();expect(exported).not.toContain(folder);
  // A denied server read must be obvious even when all ordinary work counts are zero.
  const deniedUrl=baseURL+'/api/filing/scan';
  await page.route(deniedUrl,async route=>{
    if(route.request().method()!=='GET')return route.continue();
    const response=await route.fetch(),report=await response.json();
    report.files=[{id:'blocked',relativePath:'synthetic-denied.txt',byteLength:1,modifiedAt:null,error:'Folder access was denied. Allow the background Node process access to this folder in macOS Privacy & Security, then scan again.',importable:false,logId:null}];
    report.summary={newOriginals:0,alreadyImportedFiles:0,extraCopies:0,unassignedImports:0,blockedFiles:1};
    await route.fulfill({response,json:report});
  });
  await page.getByRole('button',{name:'Refresh saved statuses',exact:true}).click();
  await expect(page.locator('.stat-label').getByText('Blocked files',{exact:true})).toBeVisible();
  await expect(page.getByText('Folder access was denied for some files. Allow the background Node process access in macOS Privacy & Security, then scan again, or choose an accessible source folder.',{exact:true})).toBeVisible();
  await page.unroute(deniedUrl);
  expect(provider.calls).toHaveLength(beforeAi);expect(airdata.calls).toHaveLength(beforeAirdata);
  expect(errors).toEqual([]);page.off('pageerror',onError);
  return {errors,passed:['no automatic scan','scan leaves catalog unchanged','renamed existing original','extra copy excluded from selection','new-only selection','partial import retains successes','serial routing','unknown identity remains unassigned','refresh assignment without rescan','no upload queue in folder review','reload retains snapshot without scanning','explicit rescan discovers later file','bulk import splits into bounded batches','blocked permission warning','mobile overflow','source bytes unchanged','folder excluded from export','no provider calls']};
}
