import { runGettingStartedJourney } from './getting-started-journey.mjs';
import { runGuidedControllerJourney } from './guided-controller-journey.mjs';
import { runBeginnerControllerJourney } from './beginner-controller-journey.mjs';
import { runControllerJourney } from './controller-journey.mjs';
import { runJournalJourney } from './journal-journey.mjs';
import { runBulkAirdataJourney } from './bulk-airdata-journey.mjs';
import { runFilingJourney } from './filing-journey.mjs';
import { createFilingService } from '../../src/import-filing.mjs';
import { runAirdataJourney } from './airdata-journey.mjs';
import { mkdtemp, mkdir, readFile, readdir, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { createServer } from '../../src/server.mjs';
import { runJourney } from './journey.mjs';
import { createBrowserStore } from './test-store.mjs';
import { runDjiJourney } from './dji-journey.mjs';
import { createBrowserAi } from './test-ai.mjs';
import { checkEmptyAiSettings, runAiJourney } from './ai-journey.mjs';
import { runFleetJourney } from './fleet-journey.mjs';
import { runStatusJourney } from './status-journey.mjs';

// Reuse an existing Playwright installation without adding application dependencies.
const moduleDir = process.env.FPVBENCH_PLAYWRIGHT_DIR;
const { chromium } = await import(moduleDir ? pathToFileURL(join(moduleDir, 'index.mjs')).href : 'playwright');
const { expect } = await import(moduleDir ? pathToFileURL(join(moduleDir, 'test.mjs')).href : 'playwright/test');
const dataDir = await mkdtemp(join(tmpdir(), 'fpvbench-browser-'));
const filingFolder = await mkdtemp(join(tmpdir(), 'fpvbench-browser-records-'));
const screenshotDir = process.env.FPVBENCH_SCREENSHOT_DIR || process.argv.find(arg => arg.startsWith('--screenshot-dir='))?.slice('--screenshot-dir='.length);
let server, browser;
const provider = createBrowserAi();
const airdata = { calls: [] };
let store;
try {
  if (screenshotDir) await mkdir(screenshotDir, { recursive: true, mode: 0o700 });
  server = await createServer({ dataDir, storeFactory: async directory => { store = await createBrowserStore(directory); return store; }, aiFactory: provider.aiFactory,
    filingFactory: (directory,options)=>createFilingService(directory,{...options,defaultFolder:filingFolder}) });
  await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve));
  const baseURL = `http://127.0.0.1:${server.address().port}`;
  browser = await chromium.launch({ headless: true, ...(process.env.FPVBENCH_CHROMIUM ? { executablePath: process.env.FPVBENCH_CHROMIUM } : {}) });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  const airdataRequests = [];
  page.on("request", request => { if (new URL(request.url()).pathname.startsWith("/api/airdata")) airdataRequests.push(request.url()); });
  const baselineText = await readFile(new URL('../../examples/baseline-dump.txt', import.meta.url), 'utf8');
  const experimentText = await readFile(new URL('../../examples/experiment-diff.txt', import.meta.url), 'utf8');
  await checkEmptyAiSettings({ page, expect, baseURL, provider });
  const result = await runJourney({ page, expect, baseURL, baselineText, experimentText, screenshotDir });
  const dji = await runDjiJourney({ page, expect, baseURL, screenshotDir });
  expect(provider.calls).toHaveLength(0);
  const ai = await runAiJourney({ page, expect, baseURL, provider, experimentText, screenshotDir });
  const fleet = await runFleetJourney({ page, expect, baseURL });
  const lifecycle = await runStatusJourney({ page, expect, baseURL, baselineText });
  const uploads = await runAirdataJourney({ page, expect, baseURL, store });
  const journal=await runJournalJourney({page,expect,baseURL,baselineText,screenshotDir,provider,airdata});
  const filing=await runFilingJourney({page,expect,baseURL,folder:filingFolder,screenshotDir,provider,airdata});
  const bulkMarks=await runBulkAirdataJourney({page,expect,baseURL,folder:filingFolder,screenshotDir,provider,airdata});
  const controller = await runControllerJourney({page,expect,baseURL,screenshotDir});
  const beginner=await runBeginnerControllerJourney({page,expect,baseURL,screenshotDir});
  const guided=await runGuidedControllerJourney({page,expect,baseURL,screenshotDir});
  const gettingStarted=await runGettingStartedJourney({page,expect,baseURL});
  expect(airdataRequests).toEqual([]);
  expect((await readdir(dataDir)).some(name => name.startsWith('workspace.sqlite'))).toBe(false);
  console.log(JSON.stringify({ browser: browser.version(), ...result, controller, beginner, guided, gettingStarted, dji, ai, fleet, lifecycle, uploads, journal, filing, bulkMarks, providerCalls: provider.calls.length, airdataRequests: airdataRequests.length, persistence: 'synthetic in-memory repository; no database opened' }, null, 2));
} finally {
  if (browser) await browser.close();
  if (server?.listening) await new Promise((resolve) => server.close(resolve));
  await rm(dataDir, { recursive: true, force: true });
  await rm(filingFolder, { recursive: true, force: true });
}
