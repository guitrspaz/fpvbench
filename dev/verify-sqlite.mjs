/** Explicit operational proof with disposable SQLite only; not an automated test datasource. */
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, readFile, readdir, rm, lstat } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { randomUUID, createHash } from 'node:crypto';
import { DatabaseSync } from 'node:sqlite';
import { createStore } from '../src/store.mjs';
import { createSqliteRepository, legacySchema } from '../src/sqlite-repository.mjs';
import { parseExport } from '../src/parser.mjs';
import { restoreBackup } from '../src/restore.mjs';
import { decodeDjiFlight } from '../src/dji-import.mjs';
import { decodedDjiFixture, syntheticDjiBinary } from '../tests/helpers/dji-fixtures.mjs';

const root = await mkdtemp(join(tmpdir(), 'fpvbench-sqlite-proof-'));
const stores = new Set();
const openStore = async (directory, options) => { const store = await createStore(directory, options); stores.add(store); return store; };
const closeStore = async store => { await store.close(); stores.delete(store); };
const digest = bytes => createHash('sha256').update(bytes).digest('hex');
try {
  const directory = join(root, 'migration'); await mkdir(directory);
  const aircraftId = randomUUID(), snapshotId = randomUUID(), sessionId = randomUUID();
  const time = '2026-10-14T12:00:00.000Z';
  const rawText = '# dump all\r\n# Betaflight / TEST 4.5.1 / MSP API: 1.46\r\nset synthetic = 1\r\nsave\r\n';
  const legacy = { version: 1, aircraft: [{ id: aircraftId, name: 'Synthetic quad', kind: 'Synthetic', notes: 'Retained', baselineSnapshotId: snapshotId, createdAt: time }], snapshots: [{ id: snapshotId, aircraftId, label: 'Synthetic baseline', notes: '', filename: 'synthetic.txt', importedAt: time, sha256: digest(Buffer.from(rawText)), rawText, parsed: parseExport(rawText) }], sessions: [{ id: sessionId, aircraftId, snapshotId, title: 'Synthetic session', flownAt: time, location: '', durationMinutes: 1, battery: '', props: '', conditions: '', notes: 'Retained note', outcome: 'same', mediaRefs: [], confirmedSetup: true, createdAt: time }] };
  const legacyBytes = Buffer.from(JSON.stringify(legacy, null, 2) + '\r\n');
  await writeFile(join(directory, 'workspace.json'), legacyBytes);
  let store = await openStore(directory);
  assert.equal(store.getState().aircraft[0].id, aircraftId);
  assert.equal(store.getState().aircraft[0].baselineSnapshotId, snapshotId);
  assert.equal(store.getState().sessions[0].flightLogId, null);
  const backups = (await readdir(directory)).filter(name => name.endsWith('.json.bak'));
  assert.equal(backups.length, 1);
  assert.deepEqual(await readFile(join(directory, backups[0])), legacyBytes);
  assert.deepEqual(await readFile(join(directory, 'workspace.json')), legacyBytes);
  assert.equal((await lstat(join(directory, backups[0]))).mode & 0o777, 0o600);
  const binary13 = await decodeDjiFlight(syntheticDjiBinary(13), { filename: 'synthetic-v13.txt' });
  assert.equal(binary13.status, 'summary-only'); assert.equal(binary13.logVersion, 13);
  const binary12 = await decodeDjiFlight(syntheticDjiBinary(12), { filename: 'synthetic-v12.txt' });
  assert.equal(binary12.logVersion, 12);
  const source = Buffer.from(JSON.stringify(decodedDjiFixture()));
  const imported = await store.importFlightLog({ aircraftId, filename: 'synthetic-flight.json', sourceDevice: 'Synthetic remote', contentBase64: source.toString('base64') });
  assert.equal(imported.flightLog.status, 'decoded');
  await store.updateSession(imported.session.id, { notes: 'Manual note retained', outcome: 'better' });
  await store.updateFlightLog(imported.flightLog.id, { airdataStatus: 'uploaded' });
  assert.deepEqual(await store.getFlightOriginal(imported.flightLog.id), source);
  const exportBefore = await store.exportWorkspace();
  await assert.rejects(restoreBackup(directory, exportBefore), /already open/);
  await closeStore(store);
  const db = new DatabaseSync(join(directory, 'workspace.sqlite'));
  db.exec('PRAGMA foreign_keys=ON;');
  assert.equal(db.prepare('PRAGMA foreign_key_check').all().length, 0);
  assert.throws(() => db.prepare('INSERT INTO sessions(id,aircraft_id,payload) VALUES(?,?,?)').run(randomUUID(), 'missing', '{}'), /FOREIGN KEY/);
  const countBefore = db.prepare('SELECT COUNT(*) AS count FROM aircraft').get().count;
  db.exec('BEGIN;'); db.prepare('INSERT INTO aircraft(id,payload) VALUES(?,?)').run(randomUUID(), '{}'); db.exec('ROLLBACK;');
  assert.equal(db.prepare('SELECT COUNT(*) AS count FROM aircraft').get().count, countBefore);
  db.close();
  // Explicit disposable v2 fixture: retain payloads and exact originals through the v3 upgrade.
  const v2dir = join(root, 'v2-upgrade'); await mkdir(v2dir); await mkdir(join(v2dir, 'imports'));
  const v2db = new DatabaseSync(join(v2dir, 'workspace.sqlite')); v2db.exec(legacySchema); v2db.exec('BEGIN IMMEDIATE;');
  for (const aircraft of exportBefore.aircraft) v2db.prepare('INSERT INTO aircraft(id,baseline_snapshot_id,payload) VALUES(?,?,?)').run(aircraft.id, aircraft.baselineSnapshotId, JSON.stringify(aircraft));
  for (const snapshot of exportBefore.snapshots) v2db.prepare('INSERT INTO snapshots(id,aircraft_id,payload) VALUES(?,?,?)').run(snapshot.id, snapshot.aircraftId, JSON.stringify(snapshot));
  for (const log of exportBefore.flightLogs) v2db.prepare('INSERT INTO flight_logs(id,aircraft_id,sha256,payload) VALUES(?,?,?,?)').run(log.id, log.aircraftId, log.sha256, JSON.stringify(log));
  for (const session of exportBefore.sessions) v2db.prepare('INSERT INTO sessions(id,aircraft_id,snapshot_id,flight_log_id,payload) VALUES(?,?,?,?,?)').run(session.id, session.aircraftId, session.snapshotId, session.flightLogId, JSON.stringify(session));
  for (const group of exportBefore.telemetry) for (const [sequence, frame] of group.frames.entries()) v2db.prepare('INSERT INTO telemetry_frames VALUES(?,?,?)').run(group.flightLogId, sequence, JSON.stringify(frame));
  v2db.exec("UPDATE metadata SET value='1' WHERE key='initialized'; COMMIT;"); v2db.close();
  for (const original of exportBefore.originals) {
    const log = exportBefore.flightLogs.find(log => log.id === original.flightLogId);
    await writeFile(join(v2dir, 'imports', `${log.sha256}.bin`), Buffer.from(original.contentBase64, 'base64'), { mode: 0o600 });
  }
  const v2bytes = await readFile(join(v2dir, 'workspace.sqlite'));
  let upgraded = await openStore(v2dir);
  assert.deepEqual(await upgraded.exportWorkspace(), exportBefore);
  const v2backups = (await readdir(v2dir)).filter(name => name.startsWith('workspace-before-v3-'));
  assert.equal(v2backups.length, 1); assert.deepEqual(await readFile(join(v2dir, v2backups[0])), v2bytes);
  const unknownBytes = Buffer.from(JSON.stringify(decodedDjiFixture({ details: { ...decodedDjiFixture().details, aircraftSn: 'SYNTHETIC-O4' } })));
  const unknown = await upgraded.importFlightLog({ filename: 'synthetic-inbox.json', contentBase64: unknownBytes.toString('base64') });
  assert.equal(unknown.flightLog.aircraftId, null); assert.equal(unknown.session, null);
  await upgraded.updateFlightLog(unknown.flightLog.id, { aircraftId, rememberAircraft: true });
  assert.equal(upgraded.getFlightLog(unknown.flightLog.id).aircraftId, aircraftId);
  const v3export = await upgraded.exportWorkspace(); await closeStore(upgraded);
  upgraded = await openStore(v2dir); assert.deepEqual(await upgraded.exportWorkspace(), v3export);
  assert.equal((await readdir(v2dir)).filter(name => name.startsWith('workspace-before-v3-')).length, 1); await closeStore(upgraded);

  store = await openStore(directory);
  assert.equal(store.getState().sessions.find(session => session.id === imported.session.id).notes, 'Manual note retained');
  assert.deepEqual(await store.exportWorkspace(), exportBefore);
  assert.equal((await readdir(directory)).filter(name => name.endsWith('.json.bak')).length, 1);
  const duplicate = await store.importFlightLog({ aircraftId, filename: 'renamed.json', contentBase64: source.toString('base64') });
  assert.equal(duplicate.duplicate, true);
  assert.equal(duplicate.flightLog.airdataStatus, 'uploaded');
  await closeStore(store);
  await restoreBackup(directory, exportBefore);
  store = await openStore(directory); assert.deepEqual(await store.exportWorkspace(), exportBefore); await closeStore(store);
  const restoredDir = join(root, 'restored'); await restoreBackup(restoredDir, exportBefore);
  store = await openStore(restoredDir); assert.deepEqual(await store.exportWorkspace(), exportBefore); await closeStore(store);
  const retryDir = join(root, 'retry'); await mkdir(retryDir); await writeFile(join(retryDir, 'workspace.json'), legacyBytes);
  await assert.rejects(openStore(retryDir, { repositoryFactory: async dir => { const repository = await createSqliteRepository(dir); repository.save = () => { throw new Error('Synthetic migration failure'); }; return repository; } }), /Cannot open workspace/);
  store = await openStore(retryDir); assert.equal(store.getState().snapshots[0].id, snapshotId); await closeStore(store);
  const badDir = join(root, 'bad-json'); await mkdir(badDir); const invalidBytes = Buffer.from([0xff, 0xfe, 0x7b]); await writeFile(join(badDir, 'workspace.json'), invalidBytes);
  await assert.rejects(openStore(badDir), /Cannot open workspace/); assert.deepEqual(await readFile(join(badDir, 'workspace.json')), invalidBytes);
  const corruptDir = join(root, 'corrupt'); await mkdir(corruptDir); const corruptBytes = Buffer.from('not sqlite'); await writeFile(join(corruptDir, 'workspace.sqlite'), corruptBytes);
  await assert.rejects(openStore(corruptDir), /Cannot open workspace/); assert.deepEqual(await readFile(join(corruptDir, 'workspace.sqlite')), corruptBytes);
  const unsupportedDir = join(root, 'unsupported'); await mkdir(unsupportedDir); const unsupportedDb = new DatabaseSync(join(unsupportedDir, 'workspace.sqlite')); unsupportedDb.exec('CREATE TABLE unrelated (id INTEGER);'); unsupportedDb.close(); const unchanged = await readFile(join(unsupportedDir, 'workspace.sqlite'));
  await assert.rejects(openStore(unsupportedDir), /Cannot open workspace/); assert.deepEqual(await readFile(join(unsupportedDir, 'workspace.sqlite')), unchanged);
  console.log('SQLite operational proof passed: v2 exact backup and v3 migration/inbox assignment, schema/FKs, transactions, v1 exact backup and idempotent migration, retry, restart, originals, telemetry, complete restore, corruption rejection, and synthetic local WASM decoding.');
} finally {
  for (const store of stores) await store.close();
  await rm(root, { recursive: true, force: true });
}
